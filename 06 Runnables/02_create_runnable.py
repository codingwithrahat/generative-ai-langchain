from abc import ABC, abstractmethod

class Runnable(ABC):

  @abstractmethod
  def invoke(input_data):
    pass

import random

class Dummyllm(Runnable):

  def __init__(self):
    print('LLM Created')

  def invoke(self, prompt):

    response_list = [
        'ami llm er response'
    ]

    return {'response': random.choice(response_list)}

  def predict(self, prompt):

    response_list = [
        'hello',
        'hi'
    ]

    return {'response': random.choice(response_list)}

class DummyPromptTemplate:
  def __init__(self, template, input_var):
    self.template = template
    self.input_var = input_var

  def invoke(self, input_dict):
    return self.template.format(**input_dict)

class DummyStrOutputParser(Runnable):
  def _init_(self):
    pass

  def invoke(self, input_data):
    return input_data['response']

class RunnableConnector(Runnable):
  def __init__(self, runlist):
    self.runlist = runlist

  def invoke(self, input_data):
    for runnable in self.runlist:
      input_data = runnable.invoke(input_data)

    return input_data

llm = Dummyllm()

template = DummyPromptTemplate('hello {topic}','topic')

chain = RunnableConnector([template, llm])

result = chain.invoke({'topic' : 'bd'})

print(result)

parser = DummyStrOutputParser()

parser.invoke(result)

chain = RunnableConnector([template, llm])

chain.invoke({'topic': 'bd'})

template2 = DummyPromptTemplate(
    template = 'write something',
    input_var = ['topic']
)

chain2 = RunnableConnector([template2, llm, parser])

chain2.invoke({'topic' : 'icpc'})

final_chain = RunnableConnector([chain, chain2])

final_chain.invoke({'topic' : 'ai'})